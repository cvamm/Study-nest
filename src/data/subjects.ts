export const subjectById = (id: string | undefined | null): Subject | undefined =>
  SUBJECTS.find((s) => s.id === id);

export const chapterById = (subject: Subject, chapterId: string | null | undefined) =>
  chapterId ? subject.chapters.find((c) => c.id === chapterId) : undefined;

export const TOTAL_CHAPTERS = SUBJECTS.reduce((acc, s) => acc + s.chapters.length, 0);
